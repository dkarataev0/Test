def short_name(name: str) -> str:
    """Короткое имя для обращения: название из кавычек, иначе первые два слова."""
    if "«" in name and "»" in name:
        return name[name.index("«") + 1:name.index("»")]
    return " ".join(name.split()[:2])


def _rng(c: Company, seed: int, channel: str) -> random.Random:
    return random.Random(zlib.crc32(f"{c.id}:{seed}:{channel}".encode()))


def _issue(c: Company, rnd: random.Random) -> str | None:
    if not c.audit or not c.audit.checks:
        return None
    failed = [ISSUE_TEXT[k] for k, ok in c.audit.checks.items() if not ok and k in ISSUE_TEXT]
    return rnd.choice(failed) if failed else None


def first_message(c: Company, city: str, where: str, seed: int = 0, channel: str = "telegram") -> str:
    """Короткое уникальное первое сообщение без ссылок."""
    rnd = _rng(c, seed, channel)
    short = short_name(c.name)
    short_q = f"«{short}»"
    social_key = next((k for k in ("vk", "instagram", "telegram") if c.socials.get(k)), None)
    social = SOCIAL_WHERE.get(social_key or "", "в соцсетях")

    kind = c.kind
    issue = _issue(c, rnd) if kind == "bad_site" else None
    if kind == "bad_site" and c.audit and not c.audit.reachable:
        kind = "unreachable"
    elif kind == "bad_site" and not issue:
        kind, issue = "bad_site", "его можно заметно улучшить"
    if kind not in OBSERVE:
        kind = "no_site"

    fill = dict(short=short, short_q=short_q, city=city, where=where, social=social,
                category_low=c.category.lower(), issue=issue or "")
    parts = [
        rnd.choice(GREETINGS).format(**fill),
        rnd.choice(INTRO).format(**fill),
        rnd.choice(OBSERVE[kind]).format(**fill),
    ]
    # Польза добавляется не всегда: короткие сообщения выглядят живее
    if rnd.random() < 0.6:
        parts.append(rnd.choice(BENEFIT[niche_of(c.niche)]))
    parts.append(rnd.choice(QUESTION))

    # Первые две части иногда склеиваем в одну строку, иногда разносим - тоже против шаблонности
    head = " ".join(parts[:2]) if rnd.random() < 0.5 else parts[0] + "\n" + parts[1]
    return head + "\n" + " ".join(parts[2:])


def after_reply(c: Company, seed: int = 0) -> str:
    return _rng(c, seed, "after").choice(AFTER_REPLY)
